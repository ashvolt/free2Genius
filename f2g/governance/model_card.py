        "| Targeting policy | Turns the effect estimate into a decision under budget, do-no-harm, value-fit and fairness constraints. |",
        "| Concierge agent | Writes the per-user explanation, grounded in that user's own fee history. |",
        "",
        "## Intended use",
        "",
        "- Selecting which free-tier users to invite to the paid tier in a batch cycle.",
        "- Generating a per-user explanation of which features would save them money.",
        "- Deciding, explicitly, **not** to contact users the subscription would not benefit.",
        "",
        "## Out-of-scope use",
        "",
        "- Any credit, lending, underwriting or eligibility decision. This system must never "
        "influence access to money.",
        "- Pricing individual users differently.",
        "- Any decision with a legal or similarly significant effect on a person.",
        "- Financial, tax, investment or debt advice. The agent declines these before any "
        "model runs (`f2g/agent/scope.py`).",
        "- Operating without the value-fit gate. Disabling it changes what the system is.",
        "",
        "## Training data",
        "",
        f"- Synthetic pilot cohort, {m['split']['train'] + m['split']['valid'] + m['split']['test']:,} "
