        "",
        "| metric | value |",
        "|---|---|",
        f"| ROC AUC | {m['propensity']['roc_auc']:.4f} |",
        f"| PR AUC | {m['propensity']['pr_auc']:.4f} |",
        f"| Log loss | {m['propensity']['log_loss']:.4f} |",
        f"| Expected calibration error | {m['propensity']['calibration_error']:.4f} |",
        "",
        f"### Uplift model — {prod}",
        "",
        "AUC is deliberately **not** reported. The treatment effect is never observed for an "
